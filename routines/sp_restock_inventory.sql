-- sp_restock_inventory.sql (IBM DB2 SQL PL)
-- Updates warehouse inventory levels and creates an audit transaction log in INVENTORY_TRANSACTIONS.

CREATE PROCEDURE SP_RESTOCK_INVENTORY (
  IN  P_WAREHOUSE_ID   CHAR(4),
  IN  P_PRODUCT_ID     INTEGER,
  IN  P_RESTOCK_QTY    INTEGER,
  IN  P_OPERATOR_ID    VARCHAR(20),
  IN  P_PO_NUMBER      VARCHAR(30),
  OUT P_NEW_ON_HAND    INTEGER
)
LANGUAGE SQL
MODIFIES SQL DATA
BEGIN
  DECLARE V_CURRENT_QTY INTEGER;
  DECLARE INV_NOT_FOUND CONDITION FOR SQLSTATE '75003';

  DECLARE EXIT HANDLER FOR NOT FOUND
    SIGNAL INV_NOT_FOUND SET MESSAGE_TEXT = 'Warehouse product inventory record not found';

  SELECT ON_HAND_QTY INTO V_CURRENT_QTY
    FROM INVENTORY
   WHERE WAREHOUSE_ID = P_WAREHOUSE_ID
     AND PRODUCT_ID = P_PRODUCT_ID;

  SET P_NEW_ON_HAND = V_CURRENT_QTY + P_RESTOCK_QTY;

  UPDATE INVENTORY
     SET ON_HAND_QTY = P_NEW_ON_HAND,
         LAST_RESTOCK_DATE = CURRENT DATE,
         LAST_AUDIT_TS = CURRENT TIMESTAMP
   WHERE WAREHOUSE_ID = P_WAREHOUSE_ID
     AND PRODUCT_ID = P_PRODUCT_ID;

  INSERT INTO INVENTORY_TRANSACTIONS (
    PRODUCT_ID,
    WAREHOUSE_ID,
    TXN_TYPE,
    QUANTITY,
    REFERENCE_NO,
    OPERATOR_ID,
    NOTES
  ) VALUES (
    P_PRODUCT_ID,
    P_WAREHOUSE_ID,
    'RECEIPT',
    P_RESTOCK_QTY,
    P_PO_NUMBER,
    P_OPERATOR_ID,
    'Restock replenishment processed successfully'
  );

END;
