-- sp_refresh_customer_summary.sql  (IBM DB2 SQL PL)
-- Cursor loop with a CONTINUE HANDLER FOR NOT FOUND. This mirrors the cursor logic in the
-- legacy COBOL program INVREG (DECLARE / OPEN / FETCH / CLOSE).

CREATE PROCEDURE SP_REFRESH_CUSTOMER_SUMMARY (OUT P_ROWS INTEGER)
  LANGUAGE SQL
  MODIFIES SQL DATA
BEGIN
  DECLARE V_CUSTNO  CHAR(6);
  DECLARE V_COUNT   INTEGER;
  DECLARE V_TOTAL   DECIMAL(11,2);
  DECLARE V_LAST    DATE;
  DECLARE V_AT_END  SMALLINT DEFAULT 0;

  DECLARE C1 CURSOR FOR
    SELECT INVCUST, COUNT(*), SUM(INVTOTAL), MAX(INVDATE)
      FROM INVOICES
     GROUP BY INVCUST
     ORDER BY INVCUST;

  DECLARE CONTINUE HANDLER FOR NOT FOUND
    SET V_AT_END = 1;

  SET P_ROWS = 0;

  DELETE FROM CUSTOMER_SALES_SUMMARY;

  OPEN C1;
  FETCH C1 INTO V_CUSTNO, V_COUNT, V_TOTAL, V_LAST;

  WHILE V_AT_END = 0 DO
    INSERT INTO CUSTOMER_SALES_SUMMARY
           (CUSTNO, INVOICE_COUNT, TOTAL_SALES, LAST_INVOICE_DATE, REFRESHED_TS)
    VALUES (V_CUSTNO, V_COUNT, V_TOTAL, V_LAST, CURRENT TIMESTAMP);

    SET P_ROWS = P_ROWS + 1;
    FETCH C1 INTO V_CUSTNO, V_COUNT, V_TOTAL, V_LAST;
  END WHILE;

  CLOSE C1;
END;
