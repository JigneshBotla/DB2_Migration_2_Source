-- sp_add_customer.sql  (IBM DB2 SQL PL)
-- Exit handlers on SQLSTATE and SQLEXCEPTION, OUT parameter, audit insert.
-- P_STATUS: 0 = added, -1 = duplicate customer number, -99 = other error.

CREATE PROCEDURE SP_ADD_CUSTOMER (
  IN  P_CUSTNO  CHAR(6),
  IN  P_FNAME   VARCHAR(20),
  IN  P_LNAME   VARCHAR(30),
  IN  P_ADDR    VARCHAR(30),
  IN  P_CITY    VARCHAR(20),
  IN  P_STATE   CHAR(2),
  IN  P_ZIP     VARCHAR(10),
  OUT P_STATUS  INTEGER)
  LANGUAGE SQL
  MODIFIES SQL DATA
BEGIN
  DECLARE EXIT HANDLER FOR SQLSTATE '23505'
    SET P_STATUS = -1;
  DECLARE EXIT HANDLER FOR SQLEXCEPTION
    SET P_STATUS = -99;

  SET P_STATUS = 0;

  INSERT INTO CUSTOMERS (CUSTNO, FNAME, LNAME, ADDR, CITY, STATE, ZIPCODE)
  VALUES (P_CUSTNO, P_FNAME, P_LNAME, P_ADDR, P_CITY, P_STATE, P_ZIP);

  INSERT INTO CUSTOMER_AUDIT (CUSTNO, ACTION_CD, NOTES)
  VALUES (P_CUSTNO, 'A', 'Customer added');
END;
