-- sp_update_customer_address.sql  (IBM DB2 SQL PL)
-- Uses GET DIAGNOSTICS ... ROW_COUNT (DB2-specific) and IF / END IF.

CREATE PROCEDURE SP_UPDATE_CUSTOMER_ADDRESS (
  IN  P_CUSTNO  CHAR(6),
  IN  P_ADDR    VARCHAR(30),
  IN  P_CITY    VARCHAR(20),
  IN  P_STATE   CHAR(2),
  IN  P_ZIP     VARCHAR(10),
  OUT P_ROWS    INTEGER)
  LANGUAGE SQL
  MODIFIES SQL DATA
BEGIN
  DECLARE V_ROWS INTEGER DEFAULT 0;

  UPDATE CUSTOMERS
     SET ADDR    = P_ADDR,
         CITY    = P_CITY,
         STATE   = P_STATE,
         ZIPCODE = P_ZIP
   WHERE CUSTNO = P_CUSTNO;

  GET DIAGNOSTICS V_ROWS = ROW_COUNT;

  IF V_ROWS > 0 THEN
    INSERT INTO CUSTOMER_AUDIT (CUSTNO, ACTION_CD, NOTES)
    VALUES (P_CUSTNO, 'U', 'Address changed');
  END IF;

  SET P_ROWS = V_ROWS;
END;
