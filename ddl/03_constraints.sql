-- 03_constraints.sql  (IBM DB2 LUW)
-- Foreign keys and a check constraint added after table creation (ALTER TABLE ... ADD CONSTRAINT).

ALTER TABLE INVOICES
      ADD CONSTRAINT INV_CUST_FK FOREIGN KEY (INVCUST)
      REFERENCES CUSTOMERS (CUSTNO);

ALTER TABLE INVOICES
      ADD CONSTRAINT INV_PROM_FK FOREIGN KEY (INVPROM)
      REFERENCES PROMOTIONS (PROMO_CODE);

ALTER TABLE INVOICE_LINES
      ADD CONSTRAINT LINES_INV_FK FOREIGN KEY (INVNO)
      REFERENCES INVOICES (INVNO)
      ON DELETE CASCADE;

ALTER TABLE INVOICE_LINES
      ADD CONSTRAINT LINES_PROD_FK FOREIGN KEY (PRODUCT_ID)
      REFERENCES PRODUCTS (PRODUCT_ID);

-- Constraints for Orders and Inventory
ALTER TABLE ORDERS
      ADD CONSTRAINT ORDERS_CUST_FK FOREIGN KEY (CUSTNO)
      REFERENCES CUSTOMERS (CUSTNO);

ALTER TABLE ORDER_ITEMS
      ADD CONSTRAINT ITEMS_ORDER_FK FOREIGN KEY (ORDER_ID)
      REFERENCES ORDERS (ORDER_ID)
      ON DELETE CASCADE;

ALTER TABLE ORDER_ITEMS
      ADD CONSTRAINT ITEMS_PROD_FK FOREIGN KEY (PRODUCT_ID)
      REFERENCES PRODUCTS (PRODUCT_ID);

ALTER TABLE INVENTORY
      ADD CONSTRAINT INV_PROD_FK FOREIGN KEY (PRODUCT_ID)
      REFERENCES PRODUCTS (PRODUCT_ID);

ALTER TABLE INVENTORY_TRANSACTIONS
      ADD CONSTRAINT TXN_PROD_FK FOREIGN KEY (PRODUCT_ID)
      REFERENCES PRODUCTS (PRODUCT_ID);

