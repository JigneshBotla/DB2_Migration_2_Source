-- 01_tables.sql  (IBM DB2 LUW)
-- Core Murach legacy schema: CUSTOMERS, INVOICES, PROMOTIONS, PRODUCTS, INVOICE_LINES.
-- Extended legacy enterprise schema: ORDERS, ORDER_ITEMS, INVENTORY, INVENTORY_TRANSACTIONS.
CREATE TABLE CUSTOMERS (
       CUSTNO            CHAR(6) NOT NULL,
       FNAME             CHAR(20) NOT NULL,
       LNAME             CHAR(30) NOT NULL,
       ADDR              CHAR(30) NOT NULL,
       CITY              CHAR(20) NOT NULL,
       STATE             CHAR(2) NOT NULL,
       ZIPCODE           CHAR(10) NOT NULL,
     CONSTRAINT CUSTNO_PK PRIMARY KEY
     (CUSTNO)
);

CREATE TABLE INVOICES (
       INVCUST            CHAR(6) NOT NULL,
       INVNO              CHAR(6) NOT NULL,
       INVDATE            DATE NOT NULL,
       INVSUBT            DECIMAL(9,2) NOT NULL,
       INVSHIP            DECIMAL(7,2) NOT NULL,
       INVTAX             DECIMAL(7,2) NOT NULL,
       INVTOTAL           DECIMAL(9,2) NOT NULL,
       INVPROM            CHAR(10) NOT NULL,
     CONSTRAINT INVNO_PK PRIMARY KEY
     (INVNO)
);

CREATE TABLE PROMOTIONS (
       PROMO_CODE         CHAR(10) NOT NULL,
       PROMO_NAME         VARCHAR(60) NOT NULL,
       DISCOUNT_PCT       DECIMAL(5,2) NOT NULL,
       START_DATE         DATE NOT NULL,
       END_DATE           DATE,
     CONSTRAINT PROMOTIONS_PK PRIMARY KEY (PROMO_CODE),
     CONSTRAINT PROMO_PCT_CK CHECK (DISCOUNT_PCT BETWEEN 0 AND 100)
);

CREATE TABLE PRODUCTS (
       PRODUCT_ID         INTEGER NOT NULL
                          GENERATED ALWAYS AS IDENTITY (START WITH 1000 INCREMENT BY 1),
       SKU                VARCHAR(20) NOT NULL,
       PRODUCT_NAME       VARCHAR(100) NOT NULL,
       CATEGORY           VARCHAR(30) NOT NULL,
       LIST_PRICE         DECIMAL(9,2) NOT NULL,
       ACTIVE_FLAG        CHAR(1) NOT NULL DEFAULT 'Y',
       CREATED_TS         TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
       DESCRIPTION        CLOB(1M),
     CONSTRAINT PRODUCTS_PK PRIMARY KEY (PRODUCT_ID),
     CONSTRAINT PRODUCTS_SKU_UQ UNIQUE (SKU),
     CONSTRAINT PRODUCTS_PRICE_CK CHECK (LIST_PRICE >= 0),
     CONSTRAINT PRODUCTS_ACTIVE_CK CHECK (ACTIVE_FLAG IN ('Y', 'N'))
);

CREATE TABLE INVOICE_LINES (
       LINE_ID            INTEGER NOT NULL
                          GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
       INVNO              CHAR(6) NOT NULL,
       LINE_NO            SMALLINT NOT NULL,
       PRODUCT_ID         INTEGER NOT NULL,
       QUANTITY           INTEGER NOT NULL,
       UNIT_PRICE         DECIMAL(9,2) NOT NULL,
       LINE_TOTAL         DECIMAL(11,2) NOT NULL,
     CONSTRAINT LINES_PK PRIMARY KEY (LINE_ID),
     CONSTRAINT LINES_INV_LINE_UQ UNIQUE (INVNO, LINE_NO),
     CONSTRAINT LINES_QTY_CK CHECK (QUANTITY > 0)
);

CREATE TABLE CUSTOMER_AUDIT (
       AUDIT_ID           INTEGER NOT NULL
                          GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
       CUSTNO             CHAR(6) NOT NULL,
       ACTION_CD          CHAR(1) NOT NULL,
       ACTION_TS          TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
       ACTION_USER        VARCHAR(128) NOT NULL DEFAULT USER,
       NOTES              VARCHAR(200),
     CONSTRAINT AUDIT_PK PRIMARY KEY (AUDIT_ID)
);

CREATE TABLE CUSTOMER_SALES_SUMMARY (
       CUSTNO             CHAR(6) NOT NULL,
       INVOICE_COUNT      INTEGER NOT NULL,
       TOTAL_SALES        DECIMAL(11,2) NOT NULL,
       LAST_INVOICE_DATE  DATE,
       REFRESHED_TS       TIMESTAMP NOT NULL,
     CONSTRAINT SUMMARY_PK PRIMARY KEY (CUSTNO)
);

CREATE TABLE ORDERS (
       ORDER_ID           INTEGER NOT NULL
                          GENERATED ALWAYS AS IDENTITY (START WITH 5000 INCREMENT BY 1),
       ORDER_NO           CHAR(8) NOT NULL,
       CUSTNO             CHAR(6) NOT NULL,
       ORDER_DATE         DATE NOT NULL,
       REQUIRED_DATE      DATE NOT NULL,
       SHIPPED_DATE       DATE,
       STATUS             VARCHAR(15) NOT NULL DEFAULT 'PENDING',
       SUBTOTAL           DECIMAL(11,2) NOT NULL DEFAULT 0.00,
       TAX_AMOUNT         DECIMAL(9,2) NOT NULL DEFAULT 0.00,
       FREIGHT_CHARGE     DECIMAL(9,2) NOT NULL DEFAULT 0.00,
       TOTAL_AMOUNT       DECIMAL(11,2) NOT NULL DEFAULT 0.00,
       PAYMENT_METHOD     VARCHAR(20) NOT NULL DEFAULT 'CREDIT',
       PAYMENT_STATUS     VARCHAR(15) NOT NULL DEFAULT 'UNPAID',
       CREATED_TS         TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
       UPDATED_TS         TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
     CONSTRAINT ORDERS_PK PRIMARY KEY (ORDER_ID),
     CONSTRAINT ORDERS_NO_UQ UNIQUE (ORDER_NO),
     CONSTRAINT ORDERS_STATUS_CK CHECK (STATUS IN ('PENDING', 'PROCESSING', 'SHIPPED', 'DELIVERED', 'CANCELLED', 'ON_HOLD')),
     CONSTRAINT ORDERS_PAY_STATUS_CK CHECK (PAYMENT_STATUS IN ('UNPAID', 'AUTHORIZED', 'PAID', 'REFUNDED'))
);

CREATE TABLE ORDER_ITEMS (
       ITEM_ID            INTEGER NOT NULL
                          GENERATED ALWAYS AS IDENTITY (START WITH 10000 INCREMENT BY 1),
       ORDER_ID           INTEGER NOT NULL,
       LINE_NO            SMALLINT NOT NULL,
       PRODUCT_ID         INTEGER NOT NULL,
       QUANTITY           INTEGER NOT NULL,
       UNIT_PRICE         DECIMAL(9,2) NOT NULL,
       DISCOUNT_PCT       DECIMAL(5,2) NOT NULL DEFAULT 0.00,
       EXTENDED_PRICE     DECIMAL(11,2) NOT NULL,
     CONSTRAINT ORDER_ITEMS_PK PRIMARY KEY (ITEM_ID),
     CONSTRAINT ORDER_ITEMS_UQ UNIQUE (ORDER_ID, LINE_NO),
     CONSTRAINT ORDER_ITEMS_QTY_CK CHECK (QUANTITY > 0),
     CONSTRAINT ORDER_ITEMS_DISC_CK CHECK (DISCOUNT_PCT BETWEEN 0.00 AND 100.00)
);

CREATE TABLE INVENTORY (
       WAREHOUSE_ID       CHAR(4) NOT NULL,
       PRODUCT_ID         INTEGER NOT NULL,
       ON_HAND_QTY        INTEGER NOT NULL DEFAULT 0,
       ALLOCATED_QTY      INTEGER NOT NULL DEFAULT 0,
       REORDER_POINT      INTEGER NOT NULL DEFAULT 10,
       REORDER_QTY        INTEGER NOT NULL DEFAULT 50,
       SAFETY_STOCK       INTEGER NOT NULL DEFAULT 5,
       BIN_LOCATION       VARCHAR(20) NOT NULL,
       LAST_RESTOCK_DATE  DATE,
       LAST_AUDIT_TS      TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
     CONSTRAINT INVENTORY_PK PRIMARY KEY (WAREHOUSE_ID, PRODUCT_ID),
     CONSTRAINT INV_ON_HAND_CK CHECK (ON_HAND_QTY >= 0),
     CONSTRAINT INV_ALLOC_CK CHECK (ALLOCATED_QTY >= 0)
);

CREATE TABLE INVENTORY_TRANSACTIONS (
       TXN_ID             INTEGER NOT NULL
                          GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
       TXN_TS             TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
       PRODUCT_ID         INTEGER NOT NULL,
       WAREHOUSE_ID       CHAR(4) NOT NULL,
       TXN_TYPE           VARCHAR(15) NOT NULL,
       QUANTITY           INTEGER NOT NULL,
       REFERENCE_NO       VARCHAR(30),
       OPERATOR_ID        VARCHAR(20) NOT NULL DEFAULT 'SYSTEM',
       NOTES              VARCHAR(255),
     CONSTRAINT INV_TXN_PK PRIMARY KEY (TXN_ID),
     CONSTRAINT INV_TXN_TYPE_CK CHECK (TXN_TYPE IN ('RECEIPT', 'SHIPMENT', 'ALLOCATION', 'DEALLOCATION', 'ADJUSTMENT', 'RETURN'))
);
