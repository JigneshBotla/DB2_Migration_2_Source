CREATE VIEW V_CUSTOMER_INVOICES AS
SELECT C.CUSTNO,
       RTRIM(C.FNAME) || ' ' || RTRIM(C.LNAME) AS CUSTOMER_NAME,
       C.STATE,
       I.INVNO,
       I.INVDATE,
       I.INVTOTAL,
       I.INVPROM
FROM CUSTOMERS C
     INNER JOIN INVOICES I
     ON I.INVCUST = C.CUSTNO;

CREATE VIEW V_INVOICE_DETAIL AS
SELECT I.INVNO,
       I.INVDATE,
       I.INVCUST,
       L.LINE_NO,
       P.SKU,
       P.PRODUCT_NAME,
       L.QUANTITY,
       L.UNIT_PRICE,
       L.LINE_TOTAL
FROM INVOICES I
     INNER JOIN INVOICE_LINES L ON L.INVNO = I.INVNO
     INNER JOIN PRODUCTS P ON P.PRODUCT_ID = L.PRODUCT_ID;

CREATE VIEW V_MONTHLY_SALES AS
SELECT YEAR(INVDATE) AS SALES_YEAR,
       MONTH(INVDATE) AS SALES_MONTH,
       COUNT(*) AS INVOICE_COUNT,
       SUM(INVTOTAL) AS TOTAL_SALES,
       AVG(INVTOTAL) AS AVG_INVOICE
FROM INVOICES
GROUP BY YEAR(INVDATE), MONTH(INVDATE);

CREATE VIEW V_PRODUCT_SALES AS
SELECT P.SKU,
       P.PRODUCT_NAME,
       P.CATEGORY,
       COALESCE(SUM(L.QUANTITY), 0) AS UNITS_SOLD,
       COALESCE(SUM(L.LINE_TOTAL), 0) AS REVENUE
FROM PRODUCTS P
     LEFT OUTER JOIN INVOICE_LINES L
     ON L.PRODUCT_ID = P.PRODUCT_ID
GROUP BY P.SKU, P.PRODUCT_NAME, P.CATEGORY;

CREATE VIEW V_PROMO_USAGE AS
SELECT R.PROMO_CODE,
       R.PROMO_NAME,
       R.DISCOUNT_PCT,
       COUNT(I.INVNO) AS INVOICES_USED,
       COALESCE(SUM(I.INVTOTAL), 0) AS SALES_WITH_PROMO
FROM PROMOTIONS R
     LEFT OUTER JOIN INVOICES I
     ON I.INVPROM = R.PROMO_CODE
GROUP BY R.PROMO_CODE, R.PROMO_NAME, R.DISCOUNT_PCT;

CREATE VIEW V_ORDER_FULFILLMENT_STATUS AS
SELECT O.ORDER_ID,
       O.ORDER_NO,
       O.CUSTNO,
       RTRIM(C.FNAME) || ' ' || RTRIM(C.LNAME) AS CUSTOMER_NAME,
       C.STATE,
       O.ORDER_DATE,
       O.REQUIRED_DATE,
       O.SHIPPED_DATE,
       CASE
         WHEN O.SHIPPED_DATE IS NOT NULL THEN (DAYS(O.SHIPPED_DATE) - DAYS(O.ORDER_DATE))
         ELSE NULL
       END AS FULFILLMENT_DAYS,
       O.STATUS,
       O.TOTAL_AMOUNT,
       COUNT(OI.ITEM_ID) AS ITEM_COUNT,
       COALESCE(SUM(OI.QUANTITY), 0) AS TOTAL_UNITS
FROM ORDERS O
     INNER JOIN CUSTOMERS C ON C.CUSTNO = O.CUSTNO
     LEFT OUTER JOIN ORDER_ITEMS OI ON OI.ORDER_ID = O.ORDER_ID
GROUP BY O.ORDER_ID, O.ORDER_NO, O.CUSTNO, C.FNAME, C.LNAME, C.STATE,
         O.ORDER_DATE, O.REQUIRED_DATE, O.SHIPPED_DATE, O.STATUS, O.TOTAL_AMOUNT;

CREATE VIEW V_INVENTORY_RESTOCK_ALERT AS
SELECT I.WAREHOUSE_ID,
       P.PRODUCT_ID,
       P.SKU,
       P.PRODUCT_NAME,
       I.ON_HAND_QTY,
       I.ALLOCATED_QTY,
       (I.ON_HAND_QTY - I.ALLOCATED_QTY) AS AVAILABLE_QTY,
       I.REORDER_POINT,
       I.REORDER_QTY,
       I.SAFETY_STOCK,
       I.BIN_LOCATION,
       CASE
         WHEN (I.ON_HAND_QTY - I.ALLOCATED_QTY) <= I.SAFETY_STOCK THEN 'CRITICAL'
         WHEN (I.ON_HAND_QTY - I.ALLOCATED_QTY) <= I.REORDER_POINT THEN 'REORDER_NOW'
         ELSE 'HEALTHY'
       END AS INVENTORY_STATUS
FROM INVENTORY I
     INNER JOIN PRODUCTS P ON P.PRODUCT_ID = I.PRODUCT_ID
WHERE (I.ON_HAND_QTY - I.ALLOCATED_QTY) <= I.REORDER_POINT;

CREATE VIEW V_CUSTOMER_360_ORDERS AS
SELECT C.CUSTNO,
       RTRIM(C.FNAME) || ' ' || RTRIM(C.LNAME) AS CUSTOMER_NAME,
       C.CITY,
       C.STATE,
       COUNT(O.ORDER_ID) AS TOTAL_ORDERS,
       COALESCE(SUM(O.TOTAL_AMOUNT), 0.00) AS LIFETIME_ORDER_VALUE,
       MAX(O.ORDER_DATE) AS LAST_ORDER_DATE,
       SUM(CASE WHEN O.STATUS IN ('PENDING', 'PROCESSING') THEN 1 ELSE 0 END) AS OPEN_ORDERS_COUNT
FROM CUSTOMERS C
     LEFT OUTER JOIN ORDERS O ON O.CUSTNO = C.CUSTNO
GROUP BY C.CUSTNO, C.FNAME, C.LNAME, C.CITY, C.STATE;

